std::string core_message_en(const std::string& de) {
    std::string out = de;
    for (const auto& [from, to] : kFragments) {
        const std::string f = from;
        for (std::size_t pos = out.find(f); pos != std::string::npos; pos = out.find(f, pos + std::string(to).size())) out.replace(pos, f.size(), to);
    }
    return out;
}

