"""Erzeugt docs/RULE_TABLE.md (Deutsch) und docs/en/RULE_TABLE.md (Englisch) aus knowledge/rules.json
(Uebersicht aller Regeln: Kennung, Stufe, Firmware, Reparatur, Nachweis, erster Satz).

Aufruf:  python3 tools/gen_rule_table.py          (schreibt beide Dateien)
         python3 tools/gen_rule_table.py --check  (Exitcode 1, wenn eine der Dateien nicht zur rules.json passt)
Die Tabellen sind erzeugt, nicht von Hand zu pflegen. Die englische Fassung nimmt den englischen Regeltext (text.en).
"""
import json
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(REPO, "docs", "RULE_TABLE.md")
OUT_EN = os.path.join(REPO, "docs", "en", "RULE_TABLE.md")


def first_sentence(text):
    m = re.match(r"(.+?[.!?])(\s|$)", text.strip(), re.S)
    s = (m.group(1) if m else text.strip()).replace("|", "/").replace("\n", " ")
    return s if len(s) <= 140 else s[:137].rstrip() + "..."


def build(lang="de"):
    en = lang == "en"
    d = json.load(open(os.path.join(REPO, "knowledge", "rules.json"), encoding="utf-8"))
    rules = d["rules"]
    if en:
        title = "# Rule overview"
        switch = "[Deutsch](../RULE_TABLE.md) · **English**"
        note = f"Generated by `tools/gen_rule_table.py` from `knowledge/rules.json` (db_version {d['db_version']}, {len(rules)} rules). Do not edit by hand."
        header = "| Rule | Level | Firmware | Repair | Evidence | Statement |"
        all_fw = "all"
    else:
        title = "# Regel-Uebersicht"
        switch = "**Deutsch** · [English](en/RULE_TABLE.md)"
        note = f"Erzeugt von `tools/gen_rule_table.py` aus `knowledge/rules.json` (db_version {d['db_version']}, {len(rules)} Regeln). Nicht von Hand aendern."
        header = "| Regel | Stufe | Firmware | Reparatur | Nachweis | Aussage |"
        all_fw = "alle"
    lines = [
        "<!-- SPDX-License-Identifier: GPL-3.0-or-later -->",
        title,
        "",
        switch,
        "",
        note,
        "",
        header,
        "|---|---|---|---|---|---|",
    ]
    for r in sorted(rules, key=lambda r: r["id"]):
        lines.append("| `{}` | {} | {} | {} | {} | {} |".format(
            r["id"], r.get("severity", ""), r.get("applies_fw") or all_fw, f"`{r['fix']}`" if r.get("fix") else "-", r.get("verified", ""), first_sentence(r["text"][lang])))
    return "\n".join(lines) + "\n"


def main():
    targets = [(OUT, build("de")), (OUT_EN, build("en"))]
    if "--check" in sys.argv:
        for path, text in targets:
            cur = open(path, encoding="utf-8", newline="").read().replace("\r\n", "\n") if os.path.exists(path) else ""
            if cur != text:
                return 1
        return 0
    for path, text in targets:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        open(path, "w", encoding="utf-8", newline="\n").write(text)
        print("geschrieben:", path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
